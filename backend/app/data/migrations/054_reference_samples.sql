--
-- 给「别人的内容」一个位置。此前 imported_notes 在结构上假设每一行都是用户自己的
-- 作品——owner_user_id 是唯一身份，没有作者/来源列；而 benchmark_samples 是纯数值
-- 基线表（无标题、无正文、无作者），装不进需要读文本的东西。于是"对标账号"无处可放。
--
--   origin         'self' | 'reference'；默认 'self'，老数据语义不变
