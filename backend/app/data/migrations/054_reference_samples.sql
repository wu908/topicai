-- 自有历史的 90 天是隐私窗口；参考样本是用户自己贴进来的"我想做成这样"，静默过期
-- 会让锚点凭空消失。
--
-- 关键不变式（由 test_reference_samples 守）：参考样本可以影响"你想做成这样"，
-- 但绝不可以进入"你是谁"的画像推断——那是两件事。所有画像/机会读取都限定 origin='self'。
